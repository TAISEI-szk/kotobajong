// Usage: node build-ielts-words.js ../personal-vocab/all-words.csv
const fs = require('node:fs');
const path = require('node:path');
require('./core.js');
const { parseCsv } = require('./personal-data.js');

const source = process.argv[2];
if (!source) throw new Error('CSVのパスを指定してください');
const count = (text, pattern) => (text.match(pattern) || []).length;

// OCR sometimes splits "（補足）訳" so that the opening bracket lands in the English column,
// and reads the book's "STH" (something) as "SīH", "īH" and similar.
function cleanEnglish(text) {
  return text
    .replace(/S?[īí]+[íI]?H?|STH/g, ' sth ')
    .replace(/[（(]\s*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

function cleanJapanese(text) {
  if (count(text, /[)）]/g) <= count(text, /[(（]/g)) return text;
  return '（' + text.replace(/\(/g, '（').replace(/\)/g, '）');
}

const rows = parseCsv(fs.readFileSync(source, 'utf8'));
const compact = rows.map(row => [row.entry_no, row.group_id, cleanEnglish(row.english), cleanJapanese(row.japanese), row.page, row.review_status]);
const body = compact.map(row => JSON.stringify(row)).join(',\n');
const output = `// Generated by build-ielts-words.js. Columns: entry_no, group_id, english, japanese, page, review_status\n` +
  `window.KOTOBA_IELTS_ROWS = [\n${body}\n].map(([entry_no, group_id, english, japanese, page, review_status]) => ({ entry_no, group_id, english, japanese, page, review_status }));\n`;
fs.writeFileSync(path.join(__dirname, 'ielts-words.js'), output);
console.log(`${rows.length}語を ielts-words.js に書き出しました`);
